package net.epicfight_dd.skill.identity;

import net.epicfight_dd.Epicfight_dd;
import net.minecraft.client.Minecraft;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.player.Player;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.client.event.RenderGuiOverlayEvent;
import net.minecraftforge.client.gui.overlay.ForgeGui;
import net.minecraftforge.client.gui.overlay.VanillaGuiOverlay;
import net.minecraftforge.event.TickEvent;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;

// Code generated by AI (gez. Nexo)

@Mod.EventBusSubscriber(modid = Epicfight_dd.MODID, value = Dist.CLIENT)
public final class GorgedBulwarkClient {
    private GorgedBulwarkClient() {}

    private static final ResourceLocation BLINK =
            ResourceLocation.fromNamespaceAndPath(Epicfight_dd.MODID, "textures/gui/hunger_blink.png");

    private static final int BLINK_TICKS = 12;

    private static Player lastPlayer;
    private static int blinkTicksLeft = 0;
    private static int lastHurtTime = 0;
    private static int lastFood = -1;
    private static int hurtTick = -100;
    private static int foodDropTick = -100;

    private static void reset() {
        blinkTicksLeft = 0;
        lastHurtTime = 0;
        lastFood = -1;
        hurtTick = -100;
        foodDropTick = -100;
    }

    @SubscribeEvent
    public static void onClientTick(TickEvent.ClientTickEvent event) {
        if (event.phase != TickEvent.Phase.END) return;

        Player player = Minecraft.getInstance().player;
        if (player != lastPlayer) {
            reset();
            lastPlayer = player;
        }
        if (player == null || !GorgedBulwarkSkill.clientActive || player.isDeadOrDying()) {
            reset();
            return;
        }

        if (blinkTicksLeft > 0) blinkTicksLeft--;

        int now = player.tickCount;
        boolean hit = player.hurtTime > lastHurtTime;
        int food = player.getFoodData().getFoodLevel();
        boolean foodDropped = lastFood >= 0 && food < lastFood;

        if (hit) hurtTick = now;
        if (foodDropped) foodDropTick = now;

        if ((hit || foodDropped) && Math.abs(hurtTick - foodDropTick) <= 3) {
            blinkTicksLeft = BLINK_TICKS;
            hurtTick = -100;
            foodDropTick = -100;
        }

        lastHurtTime = player.hurtTime;
        lastFood = food;
    }

    @SubscribeEvent
    public static void onFoodOverlayPost(RenderGuiOverlayEvent.Post event) {
        if (!VanillaGuiOverlay.FOOD_LEVEL.id().equals(event.getOverlay().id())) return;
        if (blinkTicksLeft <= 0 || (blinkTicksLeft / 3) % 2 == 0) return;

        Minecraft mc = Minecraft.getInstance();
        Player player = mc.player;
        if (player == null || player.isDeadOrDying() || !GorgedBulwarkSkill.clientActive || mc.options.hideGui) return;
        if (mc.gameMode == null || !mc.gameMode.canHurtPlayer()) return;
        if (!(mc.gui instanceof ForgeGui gui)) return;

        int left = event.getWindow().getGuiScaledWidth() / 2 + 91;
        int top = event.getWindow().getGuiScaledHeight() - gui.rightHeight + 10;

        for (int i = 0; i < 10; i++) {
            event.getGuiGraphics().blit(BLINK, left - i * 8 - 9, top, 0, 0, 9, 9, 9, 9);
        }
    }
}