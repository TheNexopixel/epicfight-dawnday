@OnlyIn(Dist.CLIENT)
public final class DeathParticles {
    private DeathParticles() {}

    private static final double WIND_STRENGTH = 0.05D;
    private static final double LIFT = 0.03D;
    private static final float ANCHOR_CHANCE_PLAYER = 1.0F;
    private static final float ANCHOR_CHANCE_MOB = 1.0F;
    private static final int ANCHOR_PARTICLES = 3;
    private static final int VOLUME_PARTICLES = 24;
    private static final int GROUND_PARTICLES = 8;

    private static final DustColorTransitionOptions EMBER = new DustColorTransitionOptions(
            new Vector3f(1.0F, 0.82F, 0.45F), new Vector3f(0.5F, 0.5F, 0.5F), 0.6F);

    public static void tick(LivingEntity entity) {
        if (!DawnDayConfig.ENABLE_DEATH_PARTICLES.get()) return;

        boolean mob = entity instanceof Mob;
        if (entity.tickCount % (mob ? 2 : 1) != 0) return;

        ParticleEngine engine = Minecraft.getInstance().particleEngine;
        RandomSource random = entity.getRandom();
        boolean water = entity.isInWater();
        Vec3 wind = water ? Vec3.ZERO : wind(entity.level().getGameTime());
        float chance = mob ? ANCHOR_CHANCE_MOB : ANCHOR_CHANCE_PLAYER;

        for (Vec3 anchor : bodyAnchors(entity)) {
            if (anchor == null) continue;
            for (int i = 0; i < ANCHOR_PARTICLES; i++) {
                if (random.nextFloat() > chance) continue;
                emit(engine, random, water,
                        anchor.x + random.nextGaussian() * 0.12D,
                        anchor.y + random.nextGaussian() * 0.14D,
                        anchor.z + random.nextGaussian() * 0.12D,
                        wind, LIFT);
            }
        }

        for (int i = 0; i < VOLUME_PARTICLES; i++) {
            emit(engine, random, water,
                    entity.getX() + (random.nextDouble() - 0.5D) * entity.getBbWidth() * 1.2D,
                    entity.getY() + random.nextDouble() * entity.getBbHeight(),
                    entity.getZ() + (random.nextDouble() - 0.5D) * entity.getBbWidth() * 1.2D,
                    wind, LIFT);
        }

        for (int i = 0; i < GROUND_PARTICLES; i++) {
            emit(engine, random, water,
                    entity.getX() + (random.nextDouble() - 0.5D) * entity.getBbWidth() * 1.5D,
                    entity.getY() + 0.05D,
                    entity.getZ() + (random.nextDouble() - 0.5D) * entity.getBbWidth() * 1.5D,
                    wind, LIFT * 0.3D);
        }
    }

    private static Vec3 wind(long gameTime) {
        double t = gameTime;
        double angle = t * 0.002D + Math.sin(t * 0.013D) * 0.7D;
        double gust = 0.65D + 0.35D * Math.sin(t * 0.05D) * Math.sin(t * 0.021D + 1.3D);
        double strength = WIND_STRENGTH * gust;
        return new Vec3(Math.cos(angle) * strength, 0.0D, Math.sin(angle) * strength);
    }

    private static void emit(ParticleEngine engine, RandomSource random, boolean water,
                             double x, double y, double z, Vec3 wind, double lift) {
        if (water) {
            ParticleOptions type = random.nextFloat() < 0.85F ? ParticleTypes.BUBBLE : ParticleTypes.BUBBLE_POP;
            create(engine, type, x, y, z,
                    random.nextGaussian() * 0.02D, 0.04D + random.nextDouble() * 0.08D, random.nextGaussian() * 0.02D,
                    20 + random.nextInt(20), 1.0F);
            return;
        }

        double gain = 0.6D + random.nextDouble() * 1.4D;
        if (random.nextFloat() < 0.08F) gain *= 2.5D;

        double vx = wind.x * gain + random.nextGaussian() * 0.012D;
        double vy = lift * (0.5D + random.nextDouble());
        double vz = wind.z * gain + random.nextGaussian() * 0.012D;

        ParticleOptions type = random.nextFloat() < 0.65F ? ParticleTypes.WHITE_ASH : ParticleTypes.ASH;
        create(engine, type, x, y, z, vx, vy, vz, 40 + random.nextInt(50), 0.7F + random.nextFloat() * 0.6F);
    }

    private static void create(ParticleEngine engine, ParticleOptions type,
                               double x, double y, double z, double vx, double vy, double vz,
                               int lifetime, float scale) {
        Particle particle = engine.createParticle(type, x, y, z, vx, vy, vz);
        if (particle != null) {
            particle.setLifetime(lifetime);
            particle.scale(scale);
        }
    }

    private static Vec3[] bodyAnchors(LivingEntity e) {
        var a = Armatures.BIPED.get();
        return new Vec3[] {
                joint(e, a.head, 0.0F, 0.0F, 0.6F),
                joint(e, a.chest, 0.0F, 0.06F, 0.1F),
                joint(e, a.torso, 0.0F, 0.0F, 0.0F),
                joint(e, a.thighL, -0.05F, 0.06F, 0.1F),
                joint(e, a.thighR, 0.05F, 0.06F, 0.1F),
                joint(e, a.handL, 0.0F, 0.6F, 0.0F),
                joint(e, a.handR, 0.0F, 0.6F, 0.0F),
                joint(e, a.kneeL, 0.0F, 0.2F, 0.2F),
                joint(e, a.kneeR, 0.0F, 0.2F, 0.2F),
                joint(e, a.legL, 0.0F, 0.2F, 0.2F),
                joint(e, a.legR, 0.0F, 0.2F, 0.2F)
        };
    }

    private static Vec3 joint(LivingEntity e, Joint joint, float x, float y, float z) {
        return JointTrack.getJointWithTranslation(e, new Vec3f(x, y, z), joint, 1.0F);
    }

    public static void witherSwirl(LivingEntity entity) {
        if (entity.tickCount % 5 != 0) return;

        ParticleEngine engine = Minecraft.getInstance().particleEngine;
        RandomSource random = entity.getRandom();
        int count = 10 + random.nextInt(16);
        double radius = 0.66D;

        for (int i = 0; i < count; i++) {
            double theta = random.nextDouble() * 2.0D * Math.PI;
            double phi = Math.acos(2.0D * random.nextDouble() - 1.0D);
            double ox = radius * Math.sin(phi) * Math.cos(theta);
            double oy = radius * Math.sin(phi) * Math.sin(theta);
            double oz = radius * Math.cos(phi);

            create(engine, ParticleTypes.LARGE_SMOKE,
                    entity.getX() + ox, entity.getY() + oy + 0.6D, entity.getZ() + oz,
                    ox * 0.2D, oy * 0.2D, oz * 0.2D, 15, 1.1F);
        }
    }
}